#!/usr/bin/env python3
"""Resolve the few non-reflected engine functions/data Minefactor calls, from Abiotic Factor's own
PDB, into ue4ss/Minefactor/src/Symbols.hpp. Re-run after a game update (the mod refuses to call
them if the exe's build timestamp no longer matches).

    tools/gen_symbols.py [path/to/AbioticFactor-Win64-Shipping.exe]
"""
import os, re, struct, subprocess, sys

SYMBOLS = {  # C++ name in Symbols.hpp -> MSVC mangled name
    "UWorld_OverlapBlockingTestByChannel": "?OverlapBlockingTestByChannel@UWorld@@QEBA_NAEBU?$TVector@N@Math@UE@@AEBU?$TQuat@N@34@W4ECollisionChannel@@AEBUFCollisionShape@@AEBUFCollisionQueryParams@@AEBUFCollisionResponseParams@@@Z",
    "FCollisionQueryParams_DefaultQueryParam": "?DefaultQueryParam@FCollisionQueryParams@@2U1@A",
    "StaticLoadClass": "?StaticLoadClass@@YAPEAVUClass@@PEAV1@PEAVUObject@@PEB_W2IPEAVUPackageMap@@@Z",
    "StaticLoadObject": "?StaticLoadObject@@YAPEAVUObject@@PEAVUClass@@PEAV1@PEB_W2IPEAVUPackageMap@@_NPEBVFLinkerInstancingContext@@@Z",
    "UTexture_UpdateResource": "?UpdateResource@UTexture@@UEAAXXZ",
}

exe = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser(
    "~/.local/share/Steam/steamapps/common/AbioticFactor/AbioticFactor/Binaries/Win64/AbioticFactor-Win64-Shipping.exe")
pdb = exe[:-4] + ".pdb"
with open(exe, "rb") as f:
    head = f.read(4096)
pe = struct.unpack_from("<I", head, 0x3C)[0]
timestamp = struct.unpack_from("<I", head, pe + 8)[0]

sections = re.findall(r"^\s+(\S+) name\n\s+([0-9A-F]+) virtual size\n\s+([0-9A-F]+) virtual address",
                      subprocess.run(["llvm-pdbutil", "dump", "--section-headers", pdb], capture_output=True, text=True).stdout, re.M)
section_va = [int(va, 16) for _, _, va in sections]

out = subprocess.run(["llvm-pdbutil", "dump", "--publics", pdb], capture_output=True, text=True).stdout
rva = {}
for name, mangled in SYMBOLS.items():
    m = re.search(re.escape("`" + mangled + "`") + r"\n\s+flags = [^,]+, addr = (\d+):(\d+)", out)
    if not m:
        sys.exit(f"{mangled} not in the PDB")
    rva[name] = section_va[int(m.group(1)) - 1] + int(m.group(2))

dst = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "ue4ss", "Minefactor", "src", "Symbols.hpp")
with open(dst, "w") as f:
    f.write("#pragma once\n// Generated by tools/gen_symbols.py from the game's PDB. Do not edit.\n#include <cstdint>\n\n")
    f.write("namespace mf::sym\n{\n")
    f.write(f"    inline constexpr std::uint32_t kExeTimestamp = 0x{timestamp:08X};\n")
    for name, value in rva.items():
        f.write(f"    inline constexpr std::uintptr_t {name} = 0x{value:X};\n")
    f.write("}\n")
print(open(dst).read())
